package dev.vexelray.installer.core;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.node.ArrayNode;
import com.fasterxml.jackson.databind.node.ObjectNode;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.time.ZoneOffset;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.regex.Pattern;

/**
 * Stages and hashes the artifacts, renders each platform's scripts, merges the manifest (history is
 * kept) and writes the README. Knows nothing about Maven or any particular operating system.
 */
public final class InstallerGenerator {
    private static final Pattern ID = Pattern.compile("[a-z0-9][a-z0-9._-]*");
    private static final Pattern BAD_NAME = Pattern.compile("[\\\\/:*?\"<>|]");
    private static final Pattern REPO = Pattern.compile("[\\w.-]+/[\\w.-]+");
    private static final Pattern EXTENSION = Pattern.compile("\\.[a-z0-9][a-z0-9_-]*");
    private static final Pattern MIME = Pattern.compile("[\\w.+-]+/[\\w.+-]+");
    /** Extensions Windows runs or treats as code; taking one over would change how it executes. */
    private static final java.util.Set<String> RESERVED_EXTENSIONS = java.util.Set.of(
            ".exe", ".com", ".bat", ".cmd", ".ps1", ".psm1", ".lnk", ".url", ".msi", ".msp", ".scr", ".pif", ".cpl",
            ".dll", ".sys", ".vbs", ".vbe", ".js", ".jse", ".wsf", ".wsh", ".hta", ".reg", ".inf", ".application");
    private static final DateTimeFormatter STAMP = DateTimeFormatter.ofPattern("yyyy-MM-dd'T'HH:mm:ss'Z'");
    static final String README_MARKER = "generated by vexelray-installer";

    private final List<PlatformTarget> targets;

    public InstallerGenerator() { this(List.of(new WindowsTarget())); }

    public InstallerGenerator(List<PlatformTarget> targets) { this.targets = List.copyOf(targets); }

    public GenerationResult generate(GenerationRequest r) {
        try {
            return run(r);
        } catch (IOException e) {
            throw new InstallerException("I/O error: " + e.getMessage(), e);
        }
    }

    private GenerationResult run(GenerationRequest r) throws IOException {
        InstallerConfig c = r.config;
        if (c == null) throw new InstallerException("no config");
        if (c.id == null || !ID.matcher(c.id).matches())
            throw new InstallerException("'id' is required: lowercase letters, digits, . _ -");
        if (InstallerConfig.blank(c.name) || BAD_NAME.matcher(c.name).find())
            throw new InstallerException("'name' is required and must be usable as a folder name");
        String version = !InstallerConfig.blank(r.version) ? r.version : c.version;
        if (InstallerConfig.blank(version))
            throw new InstallerException("no version: pass one or set 'version' in the config");
        version = Versions.strip(version);
        Versions.parse(version);

        String baseUrl = baseUrl(c.repo, c.branchOrDefault(), c.repoPathTrimmed(), r.baseUrl);
        String tag = c.tagFormatOrDefault().replace("{version}", version);
        String manifestUrl = baseUrl + "/manifest.json";

        List<PlatformTarget> active = new ArrayList<>();
        for (PlatformTarget t : targets) if (t.configOf(c) != null) active.add(t);
        if (active.isEmpty()) throw new InstallerException("config enables no platform (add a 'windows' section)");

        Path assetOut = r.assetsDir.resolve(version);
        Files.createDirectories(assetOut);
        Files.createDirectories(r.outDir);

        // 1. artifacts
        Map<PlatformTarget, List<ResolvedBinary>> resolved = new LinkedHashMap<>();
        Map<String, String> fileHashes = new LinkedHashMap<>();
        List<Path> assets = new ArrayList<>();
        for (PlatformTarget t : active) {
            PlatformConfig p = t.configOf(c);
            if (p.binaries == null || p.binaries.isEmpty())
                throw new InstallerException(t.key() + " needs at least one binary");
            for (Requirement rq : p.requires == null ? List.<Requirement>of() : p.requires) {
                if (rq.id == null || !ID.matcher(rq.id).matches())
                    throw new InstallerException("every 'requires' entry needs an 'id' (lowercase letters, digits, . _ -)");
                if (!InstallerConfig.blank(rq.min)) Versions.parse(Versions.strip(rq.min));
            }
            List<ResolvedBinary> bins = new ArrayList<>();
            java.util.Set<String> extensions = new java.util.HashSet<>();
            for (BinaryConfig b : p.binaries) {
                ResolvedBinary rb = stage(c, b, version, tag, r, assetOut);
                for (FileAssociation fa : b.fileAssociations == null ? List.<FileAssociation>of() : b.fileAssociations)
                    if (!extensions.add(normalizeExtension(fa.extension)))
                        throw new InstallerException("two binaries associate the extension '" + normalizeExtension(fa.extension) + "'");
                String prev = fileHashes.put(rb.file(), rb.sha256());
                if (prev != null && !prev.equals(rb.sha256()))
                    throw new InstallerException("two different binaries share the file name '" + rb.file() + "'");
                if (bins.stream().anyMatch(x -> x.file().equals(rb.file())))
                    throw new InstallerException("two binaries share the file name '" + rb.file() + "'");
                bins.add(rb);
                if (!assets.contains(rb.staged())) assets.add(rb.staged());
                if (rb.icon() != null) {
                    String iprev = fileHashes.put(rb.icon().file(), rb.icon().sha256());
                    if (iprev != null) throw new InstallerException("icon file name '" + rb.icon().file() + "' collides with another file; give the binaries distinct names");
                    assets.add(rb.icon().staged());
                }
            }
            resolved.put(t, bins);
        }

        // 2. scripts
        List<Path> written = new ArrayList<>();
        Map<String, String> scriptHashes = new LinkedHashMap<>();
        ObjectNode tools = Json.object();
        for (PlatformTarget t : active) {
            String installerUrl = baseUrl + "/" + t.scriptNames().get(0);
            String cfgJson = Json.compact(t.scriptConfig(c, t.configOf(c), manifestUrl)).replace("'", "''");
            for (String script : t.scriptNames()) {
                String text = Templates.lf(Templates.render(t.key() + "/" + script, Map.of(
                        "NAME", c.name, "CONFIG_JSON", cfgJson, "INSTALL_URL", installerUrl)));
                Path dest = r.outDir.resolve(script);
                writeText(dest, text, true);
                written.add(dest);
                String sha = sha256(dest);
                scriptHashes.put(script, sha);
                ObjectNode tool = tools.putObject(script);
                tool.put("url", baseUrl + "/" + script);
                tool.put("sha256", sha);
            }
        }

        // 3. manifest, merged with history
        Path manifestPath = r.outDir.resolve("manifest.json");
        String now = STAMP.format(r.clock.instant().atZone(ZoneOffset.UTC));
        List<JsonNode> history = new ArrayList<>();
        String publishedAt = now;
        boolean replaced = false;
        if (Files.exists(manifestPath)) {
            JsonNode prev = Json.tree(Files.readString(manifestPath, StandardCharsets.UTF_8));
            String prevId = prev.path("id").asText();
            if (!prevId.equals(c.id))
                throw new InstallerException("existing manifest.json is for '" + prevId + "', not '" + c.id + "'");
            for (JsonNode v : prev.path("versions")) {
                if (v.path("version").asText().equals(version)) {
                    replaced = true;
                    publishedAt = v.path("publishedAt").asText(now);
                } else {
                    history.add(v);
                }
            }
        }
        ObjectNode entry = Json.object();
        entry.put("version", version);
        entry.put("publishedAt", publishedAt);
        entry.put("notes", r.notes == null ? "" : r.notes);
        ObjectNode installer = entry.putObject("installer");
        scriptHashes.forEach(installer::put);
        ObjectNode platforms = entry.putObject("platforms");
        for (var e : resolved.entrySet()) {
            platforms.set(e.getKey().key(), e.getKey().manifestEntry(c, e.getKey().configOf(c), e.getValue()));
        }
        if (replaced) entry.put("updatedAt", now);
        history.add(entry);
        history.sort((a, b) -> Versions.NEWEST_FIRST.compare(a.path("version").asText(), b.path("version").asText()));
        String latest = history.stream().map(v -> v.path("version").asText())
                .filter(v -> !Versions.isPre(v)).findFirst()
                .orElse(history.get(0).path("version").asText());

        ObjectNode manifest = Json.object();
        manifest.put("schemaVersion", 1);
        manifest.put("id", c.id);
        manifest.put("name", c.name);
        manifest.put("publisher", c.publisherOrName());
        manifest.put("description", c.descriptionOrDefault());
        if (c.repo != null) manifest.put("repo", c.repo);
        manifest.put("latest", latest);
        manifest.set("tools", tools);
        ArrayNode versions = manifest.putArray("versions");
        history.forEach(versions::add);
        writeText(manifestPath, Json.pretty(manifest), false);
        written.add(manifestPath);

        // 4. README
        StringBuilder sections = new StringBuilder();
        String firstCommand = null;
        for (var e : resolved.entrySet()) {
            PlatformTarget t = e.getKey();
            String installerUrl = baseUrl + "/" + t.scriptNames().get(0);
            if (firstCommand == null) firstCommand = t.installCommand(installerUrl);
            sections.append(t.readmeSection(new PlatformTarget.ReadmeContext(
                    c, t.configOf(c), e.getValue(), latest, installerUrl, manifestUrl))).append('\n');
        }
        String readme = Templates.lf(Templates.render("README.md", Map.of(
                "NAME", c.name,
                "DESCRIPTION", c.descriptionOrDefault(),
                "PLATFORM_SECTIONS", sections.toString().stripTrailing() + "\n",
                "MANIFEST_URL", manifestUrl,
                "VERSION", latest)));
        Path readmePath = r.outDir.resolve("README.md");
        if (Files.exists(readmePath) && !Files.readString(readmePath, StandardCharsets.UTF_8).contains(README_MARKER)) {
            readmePath = r.outDir.resolve("INSTALL.md");
        }
        writeText(readmePath, readme, false);
        written.add(readmePath);

        return new GenerationResult(version, latest, tag, c.releasesRepoOrRepo(), manifestUrl, firstCommand,
                assets, written, r.notes == null ? "" : r.notes, Versions.isPre(version));
    }

    /**
     * The public URL of the folder the generated files are committed to: {@code override} when given,
     * otherwise that folder on raw.githubusercontent.com. Shared with {@link SuiteGenerator}, which has to
     * arrive at the same manifest URL an application's own run wrote into its scripts.
     */
    static String baseUrl(String repo, String branch, String repoPath, String override) {
        String url = override;
        if (InstallerConfig.blank(url)) {
            if (repo == null || !REPO.matcher(repo).matches())
                throw new InstallerException("'repo' must look like owner/name (the GitHub repo the generated files are committed to)");
            url = "https://raw.githubusercontent.com/" + repo + "/" + branch + (repoPath.isEmpty() ? "" : "/" + repoPath);
        }
        return url.replaceAll("/+$", "");
    }

    static boolean validId(String id) { return id != null && ID.matcher(id).matches(); }

    static void writeAscii(Path path, String text) throws IOException { writeText(path, text, true); }

    static void writeUtf8(Path path, String text) throws IOException { writeText(path, text, false); }

    private ResolvedBinary stage(InstallerConfig c, BinaryConfig b, String version, String tag,
                                 GenerationRequest r, Path assetOut) throws IOException {
        if (InstallerConfig.blank(b.source)) throw new InstallerException("every binary needs a 'source' path");
        Path src = Path.of(b.source);
        if (!src.isAbsolute()) src = r.baseDir.resolve(src);
        if (!Files.isRegularFile(src)) throw new InstallerException("artifact not found: " + src);
        String file = InstallerConfig.blank(b.file) ? src.getFileName().toString() : b.file;
        String kind = InstallerConfig.blank(b.kind)
                ? (file.endsWith(".jar") ? "jar" : file.endsWith(".zip") ? "archive" : "native") : b.kind;
        if (!kind.equals("native") && !kind.equals("jar") && !kind.equals("archive"))
            throw new InstallerException("binary kind must be 'native', 'jar' or 'archive', not '" + kind + "'");
        String name = InstallerConfig.blank(b.name) ? stem(file) : b.name;
        if (!InstallerConfig.blank(b.signedBy) && !kind.equals("native"))
            throw new InstallerException("'signedBy' only applies to native executables (" + file + ")");
        if (InstallerConfig.blank(b.signedBy) && !InstallerConfig.blank(b.signerThumbprint))
            throw new InstallerException("'signerThumbprint' needs 'signedBy' (" + file + ")");
        if (!InstallerConfig.blank(b.signerThumbprint) && !b.signerThumbprint.matches("(?i)[0-9a-f]{40}"))
            throw new InstallerException("'signerThumbprint' must be 40 hex characters (the certificate's SHA-1 thumbprint)");
        if (kind.equals("archive")) checkArchive(b, src, file);
        else if (b.exposes != null && !b.exposes.isEmpty())
            throw new InstallerException("'exposes' only applies to archive binaries (" + file + ")");
        checkAssociations(b, file);
        boolean hasJvmArgs = b.jvmArgs != null && !b.jvmArgs.isEmpty();
        if (!kind.equals("jar") && (hasJvmArgs || !InstallerConfig.blank(b.runtime)))
            throw new InstallerException("'jvmArgs' and 'runtime' only apply to jar binaries (" + file + ")");
        if (!InstallerConfig.blank(b.runtime) && !ID.matcher(b.runtime).matches())
            throw new InstallerException("'runtime' must be an install id: lowercase letters, digits, . _ -");
        if (hasJvmArgs) for (String a : b.jvmArgs) {
            if (a == null || a.isBlank() || a.matches("(?s).*[\"%\\r\\n].*"))
                throw new InstallerException("jvmArgs entries must be non-empty and contain no quotes, % or line breaks: " + a);
        }

        Path staged = assetOut.resolve(file);
        Files.copy(src, staged, StandardCopyOption.REPLACE_EXISTING);

        ResolvedBinary.ResolvedIcon icon = null;
        if (!InstallerConfig.blank(b.icon)) {
            Path isrc = Path.of(b.icon);
            if (!isrc.isAbsolute()) isrc = r.baseDir.resolve(isrc);
            if (!Files.isRegularFile(isrc)) throw new InstallerException("icon not found: " + isrc);
            String iconFile = name + ".ico";
            Path istaged = assetOut.resolve(iconFile);
            IconFiles.toIco(isrc, istaged);
            icon = new ResolvedBinary.ResolvedIcon(iconFile, assetUrl(c, r, tag, iconFile),
                    sha256(istaged), Files.size(istaged), istaged);
        }
        return new ResolvedBinary(b, name, file, kind,
                InstallerConfig.blank(b.version) ? version : b.version,
                assetUrl(c, r, tag, file), sha256(staged), Files.size(staged), staged, icon);
    }

    /** An archive is unpacked as-is, so only what makes no sense for a folder is refused here. */
    private static void checkArchive(BinaryConfig b, Path zip, String file) throws IOException {
        if (!file.endsWith(".zip")) throw new InstallerException("an archive must be a .zip file (" + file + ")");
        if (b.fileAssociations != null && !b.fileAssociations.isEmpty())
            throw new InstallerException("archive '" + file + "' cannot set fileAssociations; associate the binary that opens the files");
        if (Boolean.TRUE.equals(b.addToPath) || b.shortcuts != null || !InstallerConfig.blank(b.icon)
                || b.javaMin != null || !InstallerConfig.blank(b.runtime) || (b.jvmArgs != null && !b.jvmArgs.isEmpty()))
            throw new InstallerException("archive '" + file + "' cannot set addToPath, shortcuts, icon, javaMin, runtime or jvmArgs; "
                    + "expose commands with 'exposes' instead");
        java.util.Set<String> entries = new java.util.HashSet<>();
        try (java.util.zip.ZipFile z = new java.util.zip.ZipFile(zip.toFile())) {
            z.stream().forEach(e -> entries.add(e.getName().replace('\\', '/').toLowerCase(java.util.Locale.ROOT)));
        } catch (java.util.zip.ZipException e) {
            throw new InstallerException("not a valid zip: " + zip + " (" + e.getMessage() + ")");
        }
        if (b.exposes != null) b.exposes.forEach((cmd, rel) -> {
            if (cmd == null || !cmd.matches("[A-Za-z0-9._-]+"))
                throw new InstallerException("'exposes' command names are letters, digits, . _ - (got '" + cmd + "')");
            String norm = rel == null ? "" : rel.replace('\\', '/');
            if (norm.isBlank() || norm.startsWith("/") || norm.matches("(?s).*(^|/)\\.\\.(/|$).*") || norm.matches("(?s).*[\"%:*?<>|].*"))
                throw new InstallerException("'exposes' path for '" + cmd + "' must be relative and inside the archive: " + rel);
            if (!entries.contains(norm.toLowerCase(java.util.Locale.ROOT)))
                throw new InstallerException("'exposes' path for '" + cmd + "' is not in " + file + ": " + rel);
        });
    }

    private static void checkAssociations(BinaryConfig b, String file) {
        if (b.fileAssociations == null) return;
        java.util.Set<String> seen = new java.util.HashSet<>();
        for (FileAssociation fa : b.fileAssociations) {
            if (fa == null || InstallerConfig.blank(fa.extension))
                throw new InstallerException("every file association of " + file + " needs an 'extension'");
            String ext = normalizeExtension(fa.extension);
            if (!EXTENSION.matcher(ext).matches())
                throw new InstallerException("a file association extension is letters, digits, _ or - (got '" + fa.extension + "')");
            if (RESERVED_EXTENSIONS.contains(ext))
                throw new InstallerException("'" + ext + "' is an executable file type and cannot be associated (" + file + ")");
            if (!seen.add(ext)) throw new InstallerException(file + " lists the extension '" + ext + "' twice");
            if (!InstallerConfig.blank(fa.contentType) && !MIME.matcher(fa.contentType).matches())
                throw new InstallerException("a file association contentType looks like type/subtype (got '" + fa.contentType + "')");
            if (fa.description != null && fa.description.matches("(?s).*[\\r\\n].*"))
                throw new InstallerException("a file association description must be one line (" + ext + ")");
        }
    }

    /** {@code VXR} and {@code .vxr} both become {@code .vxr}. */
    static String normalizeExtension(String ext) {
        String e = ext.trim().toLowerCase(java.util.Locale.ROOT);
        return e.startsWith(".") ? e : "." + e;
    }

    private static String assetUrl(InstallerConfig c, GenerationRequest r, String tag, String file) {
        if (!InstallerConfig.blank(r.assetBaseUrl)) return r.assetBaseUrl.replaceAll("/+$", "") + "/" + tag + "/" + file;
        String repo = c.releasesRepoOrRepo();
        if (repo == null) throw new InstallerException("'releasesRepo' or 'repo' is required");
        return "https://github.com/" + repo + "/releases/download/" + tag + "/" + file;
    }

    private static String stem(String file) {
        int dot = file.lastIndexOf('.');
        return dot > 0 ? file.substring(0, dot) : file;
    }

    /** Scripts must stay ASCII: they are hashed, served raw, and run through {@code irm | iex}. */
    private static void writeText(Path path, String text, boolean asciiOnly) throws IOException {
        String lf = Templates.lf(text);
        if (asciiOnly) {
            for (int i = 0; i < lf.length(); i++) {
                if (lf.charAt(i) > 0x7F)
                    throw new InstallerException("non-ASCII character in " + path.getFileName()
                            + " (the scripts must stay ASCII so they survive 'irm | iex')");
            }
        }
        Files.writeString(path, lf, StandardCharsets.UTF_8);
    }

    static String sha256(Path file) throws IOException {
        try (InputStream in = Files.newInputStream(file)) {
            MessageDigest md = MessageDigest.getInstance("SHA-256");
            byte[] buf = new byte[1 << 16];
            for (int n; (n = in.read(buf)) > 0; ) md.update(buf, 0, n);
            return HexFormat.of().formatHex(md.digest());
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }
}
